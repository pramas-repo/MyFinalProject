# 3. Math. operations on Tuple
colors = ('red','yellow','green','blue','pink')
prices = (200.45, 450.30, 10000.90, 500.00, 100.00)
# addition of tuple into third using + operator
new_tuple = colors + prices
print(new_tuple)
# multiplication of tuple using * operator
new_tuple = colors * 3
print(new_tuple)
