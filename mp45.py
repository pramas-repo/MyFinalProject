# 1. Lists in Python
# Create a list
subs = ['physics','chemistry','maths','biology']
nums = [23,67,89,32,11]
# 1. Access the complete list
print(subs)
print(nums)
# 2. Access a single data in a list
print(subs[1])
print(nums[3])
sum = nums[0] + nums[3]
print(sum)
# 3. Slicing of list or cutting of list
print(subs[1:3])
print(nums[1:4])
print(nums[3:5])
print(subs[0:2])
