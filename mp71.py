# Functions in dict
# len(), min(), max(), type()
# Dict in python
employee = {'eno':10, 'name':'Rajesh Rathi','age':27,'salary':25000}
# 1. Access a dict
# a. Acess complete dict
print(employee)
print(len(employee)) # 4
print(min(employee)) # age
print(max(employee)) # salary
print(type(employee)) # <class 'dict'>